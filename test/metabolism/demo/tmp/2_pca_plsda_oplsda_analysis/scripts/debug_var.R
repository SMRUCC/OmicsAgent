# Debug script to check mixOmics PLSDA explained_variance structure
library(mixOmics)
X <- matrix(rnorm(30*10),30,10)
Y <- factor(rep(c("A","B","C"), each=10))
m <- plsda(X,Y,ncomp=2,scale=TRUE)
cat("class of explained_variance:\n")
print(class(m$explained_variance))
cat("\nnames:\n")
print(names(m$explained_variance))
cat("\nX structure:\n")
str(m$explained_variance$X)
cat("\nX values:\n")
print(m$explained_variance$X)
cat("\nY structure:\n")
str(m$explained_variance$Y)
cat("\nY values:\n")
print(m$explained_variance$Y)
