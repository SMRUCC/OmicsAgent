library(ropls)
X <- matrix(rnorm(24*10),24,10)
Y <- factor(rep(c("A","B"), each=12))
m <- opls(X, Y, predI=1, orthoI=1, fig.pdfC="none", info.txtC="none")
cat("Names of suppLs:\n")
print(names(m@suppLs))
cat("\nLength of suppLs[[\"mc\"]]:\n")
print(length(m@suppLs[["mc"]]))
cat("\nStructure:\n")
str(m@suppLs)
cat("\nOther slots:\n")
print(names(getSlots(class(m))))
